package com.mobruji.recommendation.domain;

/**
 * 추천 결과 0건(빈 화면) 방지를 위해 단계적으로 완화한 필터 종류 (#1668).
 *
 * <p>추천 생성 파이프라인의 유일한 하드 필터는 {@code excludeSongIds}(점수 계산 전 후보 제외)이다. 음역대·분위기·연령대는
 * 점수 신호일 뿐 후보를 0건으로 줄이지 않는다. 따라서 0건은 제외 곡 셋이 카탈로그를 전부 덮은 경우(특히 세션 단위 자동
 * 중복 회피 #1549 누적)에만 발생하며, 완화는 제외 필터를 가장 덜 침습적인 순서로 풀어 최소 결과를 보장한다.
 *
 * <p>음역대는 점수 순(가까운 순) 정렬로 끝까지 보존된다 — 완화 단계로 음역대 필터를 푸는 개념이 아니라, 완화된 후보를
 * 점수로 재정렬해 "완전 무관 곡"이 아닌 "가까운 곡"부터 노출한다(이슈 #1668 "음역대 마지막 / 가까운 순").
 */
public enum FilterRelaxation {

    /**
     * 세션 단위 자동 중복 회피(#1549)로 누적 제외됐던 곡(최근 추천 곡)을 다시 후보에 포함. 사용자가 이번 세션에 명시적으로
     * 제외한 곡({@code excludeSongIds})은 아직 유지한다 — 가장 덜 침습적인 1단계 완화.
     */
    SESSION_HISTORY,

    /**
     * 사용자가 명시적으로 제외한 곡까지 후보에 포함 — 그래도 0건일 때의 최종 완화. "이미 본 곡"이라도 빈 화면보다는
     * 가까운 곡을 보여 주는 편이 낫다는 판단(이슈 #1668).
     */
    EXCLUDED_SONGS
}
